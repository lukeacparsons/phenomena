// Remove pixel-scale ink irregularities, retaining the tieback and lower drape.
const knots = edges.map(frame => frame.map(side =>
  Array.from({ length: 9 }, (_, i) => {
    const row = i * 4;
    return [1, 4, 6, 4, 1].reduce((sum, weight, j) =>
      sum + weight * side[Math.max(0, Math.min(side.length - 1, row + j - 2))], 0) / 16;
  }),
));

function sample(position, side, row) {
  const i = Math.floor(position), j = Math.min(i + 1, knots.length - 1), t = position - i;
  const a = knots[i][side][row], b = knots[j][side][row];
  const before = a - knots[Math.max(0, i - 1)][side][row];
  const slope = b - a;
  const after = knots[Math.min(knots.length - 1, j + 1)][side][row] - b;
  // Monotone cubic interpolation keeps the measured opening smooth in time.
  const m0 = before * slope > 0 ? 2 * before * slope / (before + slope) : 0;
  const m1 = slope * after > 0 ? 2 * slope * after / (slope + after) : 0;
  return (2*t*t*t - 3*t*t + 1)*a + (t*t*t - 2*t*t + t)*m0
    + (-2*t*t*t + 3*t*t)*b + (t*t*t - t*t)*m1;
}

function curve(points, start) {
  const format = p => p.map(n => n.toFixed(2)).join(' ');
  let d = `${start} ${format(points[0])}`;
  for (let i = 0; i < points.length - 1; i++) {
    const p0 = points[Math.max(0, i - 1)], p1 = points[i];
    const p2 = points[i + 1], p3 = points[Math.min(points.length - 1, i + 2)];
    const a = p1.map((n, k) => n + (p2[k] - p0[k]) / 6);
    const b = p2.map((n, k) => n - (p3[k] - p1[k]) / 6);
    d += ` C ${format(a)} ${format(b)} ${format(p2)}`;
  }
  return d;
}

export function curtainEdges(progress, y) {
  const position = Math.max(0, Math.min(1, progress)) * (knots.length - 1);
  const row = Math.max(0, Math.min(1, y)) * 8;
  const i = Math.min(7, Math.floor(row)), t = row - i;
  return [0, 1].map(side => {
    const p = [-1, 0, 1, 2].map(offset => sample(position, side, Math.max(0, Math.min(8, i + offset))));
    const x = .5 * ((2*p[1]) + (-p[0]+p[2])*t + (2*p[0]-5*p[1]+4*p[2]-p[3])*t*t + (-p[0]+3*p[1]-3*p[2]+p[3])*t*t*t);
    return .5 + (x - 128) / 123;
  });
}

export function curtainAperture(progress, outside = false, width = innerWidth, height = innerHeight) {
  const position = Math.max(0, Math.min(1, progress)) * (knots.length - 1);
  const sides = [0, 1].map(side => Array.from({ length: 9 }, (_, row) => [
    (.5 + (sample(position, side, row) - 128) / 123) * width,
    row / 8 * height,
  ]));
  const opening = curve(sides[0], 'M') + curve(sides[1].reverse(), 'L') + ' Z';
  const border = `M -2 -2 H ${width + 2} V ${height + 2} H -2 Z `;
  return outside ? `path(evenodd, "${border}${opening}")` : `path("${opening}")`;
}
